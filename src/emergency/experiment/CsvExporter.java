package emergency.experiment;

import emergency.engine.SimulationConfig;
import emergency.engine.SimulationMetrics;

import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;

/**
 * Utility for exporting experiment records, metrics telemetry, and event logs
 * to CSV and Markdown report formats.
 */
public final class CsvExporter {
    private CsvExporter() {}

    /**
     * Exports a list of experiment records to standard CSV.
     */
    public static void exportExperimentsToCsv(List<ExperimentRecord> records, File targetFile) throws IOException {
        try (PrintWriter pw = new PrintWriter(new FileWriter(targetFile, StandardCharsets.UTF_8))) {
            pw.println("RunID,Name,Timestamp,Algorithm,Source,Destination,Seed,Messages,ErrorRatePct,ArrivalsPerTick,BucketCapacity,LeakRate,Delivered,DeliveryRatioPct,ThroughputMbps,AvgDelayMs,Retransmissions,CorruptedFrames,BucketDrops,Unroutable,PeakQueue,Notes");
            for (ExperimentRecord r : records) {
                SimulationConfig c = r.config;
                SimulationMetrics m = r.metrics;
                pw.printf(Locale.US,
                        "%s,\"%s\",%s,%s,%s,%s,%s,%d,%.1f,%d,%d,%d,%d,%.2f,%.4f,%.2f,%d,%d,%d,%d,%d,\"%s\"%n",
                        r.runId,
                        escapeCsv(r.name),
                        r.timestamp,
                        c.algorithm,
                        c.sourceNode,
                        c.destinationNode,
                        c.randomSeed != null ? String.valueOf(c.randomSeed) : "Random",
                        c.messageCount,
                        c.errorRate * 100.0,
                        c.arrivalsPerTick,
                        c.bucketCapacity,
                        c.leakRate,
                        m.delivered,
                        m.deliveryRatio * 100.0,
                        m.throughputMbps,
                        m.averageDelayMs,
                        m.retransmissions,
                        m.corruptedFrames,
                        m.bucketDropped,
                        m.unroutable,
                        m.peakQueue,
                        escapeCsv(r.notes)
                );
            }
        }
    }

    /**
     * Generates a comprehensive, formal Markdown project report from an experiment record.
     */
    public static String generateMarkdownReport(ExperimentRecord record) {
        if (record == null) return "# Empty Report\nNo experiment data available.";
        SimulationConfig c = record.config;
        SimulationMetrics m = record.metrics;

        StringBuilder sb = new StringBuilder();
        sb.append("# Emergency Network Simulation Report: ").append(record.name).append("\n\n");
        sb.append("**Run ID:** `").append(record.runId).append("`  \n");
        sb.append("**Execution Timestamp:** ").append(record.timestamp).append("  \n");
        sb.append("**Generated by:** Reliable Emergency Communication Network Simulator (v2.0)  \n\n");

        sb.append("## 1. Executive Summary\n");
        sb.append("This test evaluated emergency communication delivery between **")
                .append(c.sourceNode).append("** and **").append(c.destinationNode)
                .append("** using ").append(c.algorithm).append(" routing under ")
                .append(String.format(Locale.US, "%.1f%% frame error rate", c.errorRate * 100.0))
                .append(" and Leaky Bucket ingress traffic shaping (capacity: ").append(c.bucketCapacity)
                .append(", leak rate: ").append(c.leakRate).append(" pkts/tick).\n\n");

        sb.append("## 2. Input Configuration Parameters\n");
        sb.append("| Parameter | Value | Description |\n");
        sb.append("|---|---|---|\n");
        sb.append("| Offered Messages | ").append(c.messageCount).append(" | Total emergency messages generated |\n");
        sb.append("| Frame Error Rate (FER) | ").append(String.format(Locale.US, "%.1f%%", c.errorRate * 100.0)).append(" | Physical channel frame loss/corruption probability |\n");
        sb.append("| Traffic Arrival Rate | ").append(c.arrivalsPerTick).append(" pkts/tick | Ingress burst arrival frequency |\n");
        sb.append("| Leaky Bucket Capacity | ").append(c.bucketCapacity).append(" pkts | Ingress buffer depth before packet discard |\n");
        sb.append("| Leak / Service Rate | ").append(c.leakRate).append(" pkts/tick | Constant egress draining rate into network |\n");
        sb.append("| Routing Algorithm | ").append(c.algorithm).append(" | Algorithm used to determine forwarding path |\n");
        sb.append("| Random Seed | ").append(c.randomSeed != null ? c.randomSeed : "Non-deterministic (System Clock)").append(" | PRNG seed for experimental repeatability |\n");
        sb.append("| Transport Protocol | Go-Back-N ARQ (N=").append(c.windowSize).append(") | Windowed reliable sliding window ARQ with CRC-8 |\n\n");

        sb.append("## 3. Measured Experimental Results\n");
        sb.append("| Metric | Measured Value | Unit | Definition |\n");
        sb.append("|---|---|---|---|\n");
        sb.append("| Delivered Messages | ").append(m.delivered).append(" | messages | Successfully received & acknowledged messages |\n");
        sb.append("| Delivery Ratio | ").append(String.format(Locale.US, "%.2f%%", m.deliveryRatio * 100.0)).append(" | % | Delivered / Offered Messages |\n");
        sb.append("| Ingress Bucket Drops | ").append(m.bucketDropped).append(" | packets | Packets dropped due to buffer overflow |\n");
        sb.append("| Unroutable Messages | ").append(m.unroutable).append(" | messages | Dropped due to severed paths / partitioning |\n");
        sb.append("| ARQ Retransmissions | ").append(m.retransmissions).append(" | frames | Window retries triggered by loss/corruption |\n");
        sb.append("| Corrupted Frames | ").append(m.corruptedFrames).append(" | frames | Frames failing CRC-8 polynomial 0x07 check |\n");
        sb.append("| Average Delay | ").append(String.format(Locale.US, "%.2f", m.averageDelayMs)).append(" | ms | Mean end-to-end latency per delivered message |\n");
        sb.append("| Throughput | ").append(String.format(Locale.US, "%.4f", m.throughputMbps)).append(" | Mbps | Effective payload data transfer rate |\n");
        sb.append("| Peak Queue Depth | ").append(m.peakQueue).append(" | packets | Maximum queue occupancy in Leaky Bucket |\n\n");

        sb.append("## 4. Observations & Analysis\n");
        if (m.deliveryRatio >= 0.90) {
            sb.append("- **High Delivery Success:** The network delivered over 90% of offered traffic. Go-Back-N recovered corrupted frames successfully through timely retransmissions.\n");
        } else if (m.deliveryRatio >= 0.50) {
            sb.append("- **Degraded Delivery:** Moderate frame loss or queue drops reduced delivery ratio to ").append(String.format(Locale.US, "%.1f%%", m.deliveryRatio * 100.0)).append(". High retransmissions increased overall end-to-end latency.\n");
        } else {
            sb.append("- **Severe Degradation / Network Partition:** Delivery ratio collapsed below 50%. This was caused by either link failures disconnecting the destination or excessive channel error rate.\n");
        }

        if (m.bucketDropped > 0) {
            sb.append("- **Ingress Congestion Detected:** ").append(m.bucketDropped)
                    .append(" packets were discarded at the ingress Leaky Bucket because arrival rate (")
                    .append(c.arrivalsPerTick).append(") exceeded service leak rate (")
                    .append(c.leakRate).append(") and saturated capacity (").append(c.bucketCapacity).append(").\n");
        } else {
            sb.append("- **No Buffer Overflow:** Buffer capacity (").append(c.bucketCapacity)
                    .append(") was sufficient to absorb traffic bursts without packet drops.\n");
        }

        sb.append("\n---\n*Report generated on ").append(LocalDateTime.now().format(DateTimeFormatter.ISO_LOCAL_DATE_TIME)).append("*\n");
        return sb.toString();
    }

    private static String escapeCsv(String str) {
        if (str == null) return "";
        return str.replace("\"", "\"\"");
    }
}
